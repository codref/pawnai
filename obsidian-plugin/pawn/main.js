var import_obsidian16 = require("obsidian");
var SYNC_COMMAND = "sync-engine:start-non-interactive-sync";
var DEBOUNCE_MS = 1500;
var RETRY_MS = 5e3;
var MAX_BACKOFF_MS2 = 6e4;
function sleep2(ms) {
  return new Promise((resolve) => window.setTimeout(resolve, ms));
}
var VaultSync = class {
  constructor(plugin, client) {
    this.plugin = plugin;
    this.client = client;
    this.stopped = true;
    this.retry = null;
    this.kick = (0, import_obsidian16.debounce)(() => this.runSync(), DEBOUNCE_MS, true);
  }
  start() {
    if (!this.stopped)
      return;
    this.stopped = false;
    void this.loop();
  }
  stop() {
    this.stopped = true;
    this.kick.cancel();
    if (this.retry != null)
      window.clearTimeout(this.retry);
    this.retry = null;
  }
  async loop() {
    let since = 0;
    let backoff = 2e3;
    while (!this.stopped) {
      if (!this.plugin.settings.resyncOnAgentVaultWrite) {
        await sleep2(1e3);
        continue;
      }
      const started = Date.now();
      try {
        const page = await this.client.waitForVaultEvents(since);
        since = page.seq;
        if (page.resync || page.events.length > 0)
          this.kick();
        if (Date.now() - started > 5e3)
          backoff = 2e3;
      } catch (e) {
        if (this.stopped)
          return;
        await sleep2(backoff);
        backoff = Math.min(backoff * 2, MAX_BACKOFF_MS2);
      }
    }
  }
  runSync() {
    var _a;
    if (this.stopped || !this.plugin.settings.resyncOnAgentVaultWrite)
      return;
    const mgr = this.plugin.app.commands;
    if (!((_a = mgr == null ? void 0 : mgr.commands) == null ? void 0 : _a[SYNC_COMMAND]))
      return;
    if (mgr.executeCommandById(SYNC_COMMAND))
      return;
    if (this.retry != null)
      window.clearTimeout(this.retry);
    this.retry = window.setTimeout(() => {
      this.retry = null;
      if (this.stopped || !this.plugin.settings.resyncOnAgentVaultWrite)
        return;
      mgr.executeCommandById(SYNC_COMMAND);
    }, RETRY_MS);
  }
};

